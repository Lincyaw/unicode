package golang

import (
	"fmt"
	"go/token"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"testing"

	"pgregory.net/rapid"

	"github.com/lincyaw/unicode/internal/graph"
)

//uc:generates lang.golang.generation-extraction-is-read-only.sourceName
func genGenerationSourceName() *rapid.Generator[string] {
	return rapid.StringMatching(`[A-Za-z][A-Za-z0-9_]{0,12}`).Filter(token.IsIdentifier)
}

//uc:checks lang.golang.generation-extraction-is-read-only
func checkGenerationExtractionIsReadOnly(t rapid.TB, repairable, linked bool, sourceName string) {
	dir, err := os.MkdirTemp("", "unicode-generation-extract-")
	if err != nil {
		t.Fatalf("cannot make a module directory: %v", err)
	}
	defer func() { _ = os.RemoveAll(dir) }()
	current, previous := sourceName+"Current", sourceName+"Previous"
	packageLine := "package owned\n"
	header, after, filename := unicodeGeneratedHeader+"\n", "", "stale_test.go"
	if !repairable {
		switch len(sourceName) % 4 {
		case 0:
			header = ""
		case 1:
			header = "// Code generated by another tool. DO NOT EDIT.\n"
		case 2:
			header, after = "", unicodeGeneratedHeader+"\n"
		case 3:
			filename = "stale.go"
		}
	}
	stale := header + packageLine + after + fmt.Sprintf("func oldSnapshot() int { return %s() }\n", previous)
	files := map[string]string{
		"go.mod":          "module example.com/generation\n\ngo 1.26\n",
		"owned/source.go": packageLine + fmt.Sprintf("\n//uc:observes model.contract.snapshot\nfunc %s() int { return 1 }\n", current),
		// This broken generated test lies outside the configured source root.
		"unselected/unrelated_test.go": unicodeGeneratedHeader + "\npackage unselected\nvar unrelated = missingOutsideRoot\n",
	}
	stalePath := filepath.Join("owned", filename)
	if linked {
		files["unselected/target.txt"] = stale
	} else {
		files[stalePath] = stale
	}
	for name, content := range files {
		file := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(file), 0o755); err != nil {
			t.Fatalf("cannot make the directory of %s: %v", name, err)
		}
		if err := os.WriteFile(file, []byte(content), 0o644); err != nil {
			t.Fatalf("cannot write %s: %v", name, err)
		}
	}
	if linked {
		if err := os.Symlink(filepath.Join(dir, "unselected/target.txt"), filepath.Join(dir, stalePath)); err != nil {
			t.Fatalf("cannot link the stale source: %v", err)
		}
	}

	backend := NewBackend()
	if _, err := backend.Extract(dir, []string{"owned"}); err == nil || !strings.Contains(err.Error(), previous) {
		t.Fatalf("ordinary extraction must reject the old reference %s, got %v", previous, err)
	}
	extracted, err := backend.ExtractForGeneration(dir, []string{"owned"})
	if wantSuccess := repairable && !linked; (err == nil) != wantSuccess {
		t.Fatalf("generation extraction success = %t, want %t (repairable=%t, linked=%t): %v", err == nil, wantSuccess, repairable, linked, err)
	}
	if err != nil && !strings.Contains(err.Error(), previous) {
		t.Fatalf("generation extraction lost the handwritten or linked old reference: %v", err)
	}
	if err == nil {
		if len(extracted.Diagnostics) > 0 {
			t.Fatalf("the current observer has invalid bindings: %+v", extracted.Diagnostics)
		}
		adapter, generatedFile := false, false
		adapterID := "go:example.com/generation/owned." + current
		for _, node := range extracted.Fragment.Nodes {
			if node.Kind == graph.NodeKindOp && node.Id == adapterID {
				adapter = true
			}
			if node.Id == "file:owned/"+filename && slices.Contains(node.Attrs["generated"], "true") {
				generatedFile = true
			}
		}
		observes := 0
		for _, edge := range extracted.Fragment.Edges {
			if edge.Kind == graph.EdgeKindObserves && edge.From == adapterID && edge.To == "model.contract.snapshot" {
				observes++
			}
		}
		if !adapter || !generatedFile || observes != 1 {
			t.Fatalf("generation extraction lost the current observer or generated-file metadata: adapter=%t, file=%t, observes=%d", adapter, generatedFile, observes)
		}
	}
	for name, before := range files {
		after, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil || string(after) != before {
			t.Fatalf("extraction changed %s: read error %v", name, err)
		}
	}
	if linked {
		info, err := os.Lstat(filepath.Join(dir, stalePath))
		if err != nil || info.Mode()&os.ModeSymlink == 0 {
			t.Fatalf("extraction replaced the source symlink: %v", err)
		}
	}
}

func TestGenerationExtractionIsReadOnly(t *testing.T) {
	rapid.Check(t, func(t *rapid.T) {
		checkGenerationExtractionIsReadOnly(t, rapid.Bool().Draw(t, "repairable"), rapid.Bool().Draw(t, "linked"), genGenerationSourceName().Draw(t, "sourceName"))
	})
}

func FuzzGenerationExtractionIsReadOnly(f *testing.F) {
	f.Fuzz(rapid.MakeFuzz(func(t *rapid.T) {
		checkGenerationExtractionIsReadOnly(t, rapid.Bool().Draw(t, "repairable"), rapid.Bool().Draw(t, "linked"), genGenerationSourceName().Draw(t, "sourceName"))
	}))
}
