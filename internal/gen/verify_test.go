//uc:generates gen.check-files-are-current.sample
func genCheckSample() *rapid.Generator[WriteSample] { return genWriteSample() }

//uc:checks gen.check-files-are-current
func checkCheckFilesAreCurrent(t rapid.TB, sample WriteSample) {
	base, err := os.MkdirTemp("", "unicode-check-files-")
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = os.RemoveAll(base) }()
	root := filepath.Join(base, "repo")
	for _, dir := range []string{root, filepath.Join(base, "outside")} {
		if err := os.MkdirAll(dir, 0o750); err != nil {
			t.Fatal(err)
		}
	}
	if err := os.WriteFile(filepath.Join(base, "outside", "user.go"), []byte("outside"), 0o600); err != nil {
		t.Fatal(err)
	}
	for path, content := range sample.Files {
		if err := os.WriteFile(filepath.Join(root, path), []byte(content), 0o640); err != nil {
			t.Fatal(err)
		}
	}
	for path, target := range sample.Links {
		if err := os.Symlink(target, filepath.Join(root, path)); err != nil {
			t.Fatal(err)
		}
	}
	checked := checkReadOnly(t, base, root, sample.Edits)
	written := Write(root, sample.Edits)
	if len(written) > 0 {
		if !reflect.DeepEqual(checked, written) {
			t.Fatalf("CheckFiles and Write rejected the same unsafe plan differently: check %+v; write %+v", checked, written)
		}
		return
	}
	// Every file in the initial plan was absent or had bytes from the sample.
	var stale []string
	for _, edit := range sample.Edits {
		if content, exists := sample.Files[edit.Path]; !exists || !bytes.Equal([]byte(content), edit.Content) {
			stale = append(stale, edit.Path)
		}
	}
	slices.Sort(stale)
	if len(checked) != len(stale) {
		t.Fatalf("CheckFiles gave %+v, want stale files %v", checked, stale)
	}
	for i, path := range stale {
		if checked[i].Code != "gen.stale-file" || checked[i].Subject != path {
			t.Fatalf("CheckFiles diagnostic %+v does not identify stale file %s", checked[i], path)
		}
	}
	if ds := checkReadOnly(t, base, root, sample.Edits); len(ds) != 0 {
		t.Fatalf("CheckFiles rejected files just written from the same plan: %+v", ds)
	}
	if len(sample.Edits) == 0 {
		return
	}
	edit := sample.Edits[0]
	target := filepath.Join(root, filepath.FromSlash(edit.Path))
	if err := os.WriteFile(target, append(slices.Clone(edit.Content), '\n'), 0o640); err != nil {
		t.Fatal(err)
	}
	if ds := checkReadOnly(t, base, root, sample.Edits); len(ds) != 1 || ds[0].Code != "gen.stale-file" || ds[0].Subject != edit.Path {
		t.Fatalf("CheckFiles accepted or mislocated changed generated bytes: %+v", ds)
	}
	if err := os.Remove(target); err != nil {
		t.Fatal(err)
	}
	if ds := checkReadOnly(t, base, root, sample.Edits); len(ds) != 1 || ds[0].Code != "gen.stale-file" || ds[0].Subject != edit.Path {
		t.Fatalf("CheckFiles accepted or mislocated a missing generated file: %+v", ds)
	}
}

func checkReadOnly(t rapid.TB, base, root string, edits []lang.Edit) []diag.Diagnostic {
	before := checkTree(t, base)
	ds := CheckFiles(root, edits)
	if after := checkTree(t, base); !reflect.DeepEqual(before, after) {
		t.Fatalf("CheckFiles changed repository entries: before %+v; after %+v", before, after)
	}
	for _, d := range ds {
		if !strings.HasPrefix(d.Code, "gen.") || d.Subject == "" || d.Position.Path == "" || d.Position.Line < 1 || d.Position.Column < 1 || d.Message == "" || d.Fix == "" {
			t.Fatalf("CheckFiles returned an incomplete diagnostic: %+v", d)
		}
	}
	return ds
}

type checkedEntry struct {
	Mode     os.FileMode
	Modified int64
	Content  string
	Target   string
}

func checkTree(t rapid.TB, root string) map[string]checkedEntry {
	out := map[string]checkedEntry{}
	err := filepath.WalkDir(root, func(path string, entry os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		info, err := entry.Info()
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		item := checkedEntry{Mode: info.Mode(), Modified: info.ModTime().UnixNano()}
		switch {
		case info.Mode()&os.ModeSymlink != 0:
			item.Target, err = os.Readlink(path)
		case info.Mode().IsRegular():
			var content []byte
			content, err = os.ReadFile(path)
			item.Content = string(content)
		}
		out[filepath.ToSlash(rel)] = item
		return err
	})
	if err != nil {
		t.Fatal(err)
	}
	return out
}
