// This file computes from the model of a module the nodes, edges and
// diagnostics that extraction should give.

// expectation collects what the model should extract to. at holds, from
// every file written, where each declaration's name, each call's callee and
// each comment line are.
type expectation struct {
	w           *world
	at          map[any]diag.Position
	imports     map[*gfile]map[string]bool
	nodes       map[string]graph.Node
	edges       map[edgeKey]graph.Edge
	sites       map[edgeKey][]diag.Position
	diagnostics []string
	realized    map[*gtype][]string
}

func (w *world) module() Module {
	files := maps.Clone(rapidFiles)
	files["go.mod"] = goMod
	x := &expectation{
		w: w, at: map[any]diag.Position{}, imports: map[*gfile]map[string]bool{}, nodes: map[string]graph.Node{},
		edges: map[edgeKey]graph.Edge{}, sites: map[edgeKey][]diag.Position{}, realized: map[*gtype][]string{},
	}
	for _, f := range w.files() {
		written := write(f)
		files[f.path] = written.b.String()
		maps.Copy(x.at, written.at)
		x.imports[f] = written.imports
	}
	for _, ty := range w.types {
		for _, b := range bindingsOf(ty.doc, true) {
			x.realized[ty] = append(x.realized[ty], b.target)
		}
	}
	for _, p := range w.packages {
		x.addPackage(p)
	}
	x.addImplements()
	x.expectContent(files)
	m := Module{Files: files, Diagnostics: x.diagnostics}
	nodes := slices.SortedFunc(maps.Values(x.nodes), func(a, b graph.Node) int { return cmp.Compare(a.Id, b.Id) })
	for _, n := range digestClasses(nodes) {
		m.Nodes = append(m.Nodes, describeNode(n))
	}
	for key, e := range x.edges {
		if sites := x.sites[key]; len(sites) > 0 {
			slices.SortFunc(sites, func(a, b diag.Position) int {
				return cmp.Or(cmp.Compare(a.Path, b.Path), cmp.Compare(a.Line, b.Line), cmp.Compare(a.Column, b.Column))
			})
			e.Attrs = map[string][]string{"sites": {}}
			for _, s := range sites {
				e.Attrs["sites"] = append(e.Attrs["sites"], fmt.Sprintf("%s:%d:%d", s.Path, s.Line, s.Column))
			}
		}
		m.Edges = append(m.Edges, describeEdge(e))
	}
	slices.Sort(m.Nodes)
	slices.Sort(m.Edges)
	slices.Sort(m.Diagnostics)
	return m
}

func (x *expectation) addPackage(p *gpkg) {
	files := slices.SortedFunc(slices.Values(p.files), func(a, b *gfile) int { return cmp.Compare(a.path, b.path) })
	written := files[0]
	for _, f := range files {
		if len(f.doc) > 0 {
			written = f
			break
		}
	}
	pkgID := "go:" + p.path
	x.node(pkgID, graph.NodeKindContainer, "package", x.at[written], summaryOf(written.doc),
		map[string][]string{"language": {"go"}, "path": {p.path}})
	for _, f := range files {
		x.misplaced(f.doc)
		fileID := "file:" + f.path
		attrs := map[string][]string{"language": {"go"}, "path": {f.path}}
		if f.header == "// Code generated by unicode. DO NOT EDIT." && !f.headerAfterPackage {
			attrs["generated"] = []string{"true"}
		}
		if globals := plainGlobals(f); globals != "" {
			attrs["globals"] = []string{globals}
		}
		x.node(fileID, graph.NodeKindContainer, "file", x.at[f], "", attrs)
		x.edge(graph.EdgeKindContains, pkgID, fileID, graph.SourceExtracted)
		for _, imported := range x.w.packages {
			if x.imports[f][imported.path] {
				x.edge(graph.EdgeKindImports, fileID, "go:"+imported.path, graph.SourceExtracted)
			}
		}
		for _, decl := range f.decls {
			switch decl := decl.(type) {
			case *gtype:
				x.addType(decl, fileID)
			case *ggroup:
				x.misplaced(decl.doc)
				for _, ty := range decl.types {
					x.addType(ty, fileID)
				}
			case *gfunc:
				x.addFunc(decl, fileID)
			case *gvar:
				for _, e := range decl.entries {
					for i := range e.body {
						x.closureComments(&e.body[i])
					}
				}
			case *gloose:
				x.misplaced(decl.doc)
			}
		}
	}
}

func typeIdentity(ty *gtype) string { return "go:" + ty.file.pkg.path + "." + ty.name }

func funcIdentity(fn *gfunc) string {
	if fn.recv != nil {
		return typeIdentity(fn.recv) + "." + fn.sig.name
	}
	return "go:" + fn.file.pkg.path + "." + fn.sig.name
}

// summaryOf is the sentence a doc comment starts with, when it has one.
func summaryOf(doc []binding) string {
	if len(doc) == 0 {
		return ""
	}
	return strings.TrimPrefix(doc[0].text, "// ")
}

// addType expects a type's node, its declaration written in plain, so that
// two types share a digest exactly when they declare the same.
func (x *expectation) addType(ty *gtype, fileID string) {
	id := typeIdentity(ty)
	attrs := map[string][]string{"name": {ty.name}, "declaration": {plainType(ty)}}
	switch ty.form {
	case "struct":
		attrs["fields"] = []string{}
		for _, field := range ty.fields {
			x.misplaced(field.doc)
			if token.IsExported(field.name) {
				attrs["fields"] = append(attrs["fields"], lowerFirst(field.name)+": "+x.design(field.typ))
			}
			x.refers(id, field.typ)
		}
		if ty.embed != nil {
			x.edge(graph.EdgeKindExtends, id, typeIdentity(ty.embed), graph.SourceExtracted)
		}
	case "interface":
		for _, sig := range ty.sigs {
			x.addAbstract(ty, sig)
		}
		for _, e := range ty.embeds {
			x.edge(graph.EdgeKindExtends, id, typeIdentity(e), graph.SourceExtracted)
		}
	default:
		x.refers(id, ty.under)
		if values := x.values(ty); len(values) > 0 {
			attrs["values"] = values
		}
	}
	x.node(id, graph.NodeKindType, ty.form, x.at[ty], summaryOf(ty.doc), attrs)
	x.edge(graph.EdgeKindContains, fileID, id, graph.SourceExtracted)
	x.bindings(id, ty.doc, true)
}

// values are the enum values of a type's constants, in the order of its
// package's files and of the source.
func (x *expectation) values(ty *gtype) []string {
	var values []string
	files := slices.SortedFunc(slices.Values(ty.file.pkg.files), func(a, b *gfile) int { return cmp.Compare(a.path, b.path) })
	for _, f := range files {
		for _, decl := range f.decls {
			if c, ok := decl.(*gconst); ok && c.typ == ty {
				value := c.name
				if rest := strings.TrimPrefix(c.name, ty.name); rest != c.name && token.IsExported(rest) {
					value = lowerFirst(rest)
				}
				values = append(values, value)
			}
		}
	}
	return values
}

// addAbstract expects the node of a method an interface declares.
func (x *expectation) addAbstract(iface *gtype, sig *gsig) {
	id := typeIdentity(iface) + "." + sig.name
	x.op(id, "abstract", x.at[sig], sig, sig.doc, "none", false, nil)
	x.edge(graph.EdgeKindContains, typeIdentity(iface), id, graph.SourceExtracted)
	x.refersSig(id, sig)
	x.bindings(id, sig.doc, false, true)
	x.candidates(id, iface, sig.name)
}

func (x *expectation) addFunc(fn *gfunc, fileID string) {
	id := funcIdentity(fn)
	form, parent := "func", fileID
	if fn.recv != nil {
		form, parent = "method", typeIdentity(fn.recv)
	}
	testKind := "none"
	if fn.file.test && fn.recv == nil {
		switch {
		case fn.testName == "Fuzz":
			testKind = "fuzz"
		case fn.testName == "Test" && callsRapid(fn.body):
			testKind = "property"
		case fn.testName == "Test":
			testKind = "example"
		}
	}
	stub := fn.terminal == marker && !slices.ContainsFunc(fn.body, isStatement)
	x.op(id, form, x.at[fn], fn.sig, fn.doc, testKind, stub, []string{plainBody(fn)})
	x.edge(graph.EdgeKindContains, parent, id, graph.SourceExtracted)
	x.refersSig(id, fn.sig)
	x.bindings(id, fn.doc, false, fn.recv != nil)
	for i := range fn.body {
		x.addStmt(id, &fn.body[i])
	}
	x.closureCalls(id, fn.body)
	if fn.recv != nil {
		x.candidates(id, fn.recv, fn.sig.name)
	}
}

// op expects an operation's node; a function's body is written in plain,
// so that two functions share a digest exactly when their bodies are the same.
func (x *expectation) op(id, form string, at diag.Position, sig *gsig, doc []binding, testKind string, stub bool, body []string) {
	name := lowerFirst(sig.name)
	if checks(doc) {
		name = predicateOf(sig.name)
	}
	attrs := map[string][]string{
		"name": {name}, "signature": {x.signature(sig)}, "testKind": {testKind}, "stub": {strconv.FormatBool(stub)},
	}
	if body != nil {
		attrs["body"] = body
	}
	x.node(id, graph.NodeKindOp, form, at, summaryOf(doc), attrs)
}

// predicateOf is the property's or flow's name a predicate's name maps from.
func predicateOf(goName string) string {
	for _, prefix := range []string{"checkFlow", "check"} {
		if rest := strings.TrimPrefix(goName, prefix); rest != goName && token.IsExported(rest) {
			var words []string
			start := 0
			for i := 1; i < len(rest); i++ {
				if rest[i] >= 'A' && rest[i] <= 'Z' {
					words, start = append(words, strings.ToLower(rest[start:i])), i
				}
			}
			return strings.Join(append(words, strings.ToLower(rest[start:])), "-")
		}
	}
	return lowerFirst(goName)
}

// candidates expects a derived realizes edge from an exported method of a
// type that realizes design types to the operation of each its name maps to.
func (x *expectation) candidates(id string, ty *gtype, name string) {
	if token.IsExported(name) {
		for _, target := range x.realized[ty] {
			x.edge(graph.EdgeKindRealizes, id, target+"."+lowerFirst(name), graph.SourceDerived)
		}
	}
}

// isStatement tells whether a line of a body is a statement; a comment is not,
// so a stub may carry one.
func isStatement(s gstmt) bool { return s.kind != "comment" }

func callsRapid(body []gstmt) bool {
	return slices.ContainsFunc(body, func(s gstmt) bool { return s.kind == "rapid" || s.inner != nil && s.inner.kind == "rapid" })
}

// addStmt expects a statement's calls edge, a reference's too, and refers
// edges to the types its text names and its variable has.
func (x *expectation) addStmt(id string, s *gstmt) {
	switch s.kind {
	case "closure":
		x.addStmt(id, s.inner)
	case "call", "assign":
		x.call(id, funcIdentity(s.target), s)
		if s.via != nil {
			x.edge(graph.EdgeKindRefers, id, typeIdentity(s.via), graph.SourceExtracted)
		}
		for _, p := range s.target.sig.params {
			x.refers(id, p.typ)
		}
		if s.kind == "assign" {
			x.refers(id, s.target.sig.results[0])
		}
	case "iface":
		x.call(id, x.abstract(s.method), s)
		x.edge(graph.EdgeKindRefers, id, typeIdentity(s.via), graph.SourceExtracted)
		for _, p := range s.method.params {
			x.refers(id, p.typ)
		}
	case "ref", "ifaceRef":
		x.call(id, x.callee(s), s)
		if s.via != nil {
			x.edge(graph.EdgeKindRefers, id, typeIdentity(s.via), graph.SourceExtracted)
		}
	case "comment":
		x.unbound(&s.comment)
	}
}

// callee is the identity of what a statement calls or names: a function or a
// method, or an interface's method.
func (x *expectation) callee(s *gstmt) string {
	if s.method != nil {
		return x.abstract(s.method)
	}
	return funcIdentity(s.target)
}

// call expects a calls edge with the site of a statement's callee.
func (x *expectation) call(from, to string, s *gstmt) {
	key := x.edge(graph.EdgeKindCalls, from, to, graph.SourceExtracted)
	x.sites[key] = append(x.sites[key], x.at[s])
}

// abstract is the identity of the operation an interface's method is.
func (x *expectation) abstract(sig *gsig) string {
	return typeIdentity(x.declaring(sig)) + "." + sig.name
}

// closureCalls expects the calls of the closures in the variables a body
// uses and the functions and methods they store, and those of the variables
// their statements use in turn, as calls of the body's function, each
// variable's once; no refers edge comes with them.
func (x *expectation) closureCalls(id string, body []gstmt) {
	held := heldBy(body)
	seen := map[*gvar]bool{}
	for len(held) > 0 {
		v := held[0]
		held = held[1:]
		if seen[v] {
			continue
		}
		seen[v] = true
		for _, e := range v.entries {
			if e.ref != nil {
				x.call(id, funcIdentity(e.ref.target), e.ref)
			}
			for i := range e.body {
				held = append(held, x.closureStmt(id, &e.body[i])...)
			}
		}
	}
}

// closureStmt expects the call or the reference of a statement in a
// variable's closure as a call of the function id, and returns the variables
// the statement uses.
func (x *expectation) closureStmt(id string, s *gstmt) []*gvar {
	switch s.kind {
	case "closure":
		return x.closureStmt(id, s.inner)
	case "call", "assign", "iface", "ref", "ifaceRef":
		x.call(id, x.callee(s), s)
	case "varCall", "varRef":
		return []*gvar{s.held}
	}
	return nil
}

// closureComments expects a diagnostic for a //uc: line in a variable's closure.
func (x *expectation) closureComments(s *gstmt) {
	switch s.kind {
	case "closure":
		x.closureComments(s.inner)
	case "comment":
		x.unbound(&s.comment)
	}
}

// heldBy lists the variables the statements of a body use, its closures' included.
func heldBy(body []gstmt) []*gvar {
	var out []*gvar
	for _, s := range body {
		switch {
		case s.kind == "varCall" || s.kind == "varRef":
			out = append(out, s.held)
		case s.inner != nil:
			out = append(out, heldBy([]gstmt{*s.inner})...)
		}
	}
	return out
}

// declaring is the interface that declares a method.
func (x *expectation) declaring(sig *gsig) *gtype {
	for _, ty := range x.w.types {
		if slices.Contains(ty.sigs, sig) {
			return ty
		}
	}
	panic("genModule drew a call of an interface method that no interface declares")
}

// bindings expects the edges of a declaration's well-formed bindings, and a
// diagnostic for each other //uc: line of its doc comment: on a type only
// realizes binds, and a binding repeated is a duplicate.
func (x *expectation) bindings(id string, doc []binding, isType bool, method ...bool) {
	var seen []binding
	for i := range doc {
		b := doc[i]
		switch {
		case !strings.HasPrefix(b.text, "//uc:"):
			continue
		case b.code != "":
			x.diagnose(b.code, &doc[i])
			continue
		case isType && b.verb != "realizes":
			x.diagnose(codeMisplaced, &doc[i])
			continue
		case len(method) > 0 && method[0] && b.verb == "observes":
			x.diagnose(codeMisplaced, &doc[i])
			continue
		case slices.Contains(seen, b):
			x.diagnose(codeDuplicate, &doc[i])
			continue
		}
		seen = append(seen, b)
		switch b.verb {
		case "generates":
			dot := strings.LastIndex(b.target, ".")
			property, symbol := b.target[:dot], b.target[dot+1:]
			key := edgeKey{graph.EdgeKindGenerates, id, property}
			e, ok := x.edges[key]
			if !ok {
				e = graph.Edge{Kind: key.kind, From: id, To: property, Source: graph.SourceDeclared, Attrs: map[string][]string{}}
			}
			e.Attrs["symbols"] = append(e.Attrs["symbols"], symbol)
			x.edges[key] = e
		default:
			x.edge(map[string]graph.EdgeKind{"realizes": graph.EdgeKindRealizes, "checks": graph.EdgeKindChecks, "observes": graph.EdgeKindObserves, "publishes": graph.EdgeKindPublishes}[b.verb],
				id, b.target, graph.SourceDeclared)
		}
	}
}

// misplaced expects a diagnostic for each //uc: line of a comment that binds nothing.
func (x *expectation) misplaced(lines []binding) {
	for i := range lines {
		x.unbound(&lines[i])
	}
}

func (x *expectation) unbound(line *binding) {
	if strings.HasPrefix(line.text, "//uc:") {
		x.diagnose(cmp.Or(line.code, codeMisplaced), line)
	}
}

func (x *expectation) diagnose(code string, line *binding) {
	at := x.at[line]
	x.diagnostics = append(x.diagnostics, fmt.Sprintf("%s %s:%d", code, at.Path, at.Line))
}

func (x *expectation) refers(from string, e *gexpr) {
	switch e.kind {
	case "named":
		x.edge(graph.EdgeKindRefers, from, typeIdentity(e.named), graph.SourceExtracted)
	case "pointer", "slice", "map":
		x.refers(from, e.elem)
	}
}

func (x *expectation) refersSig(from string, sig *gsig) {
	for _, p := range sig.params {
		x.refers(from, p.typ)
	}
	for _, r := range sig.results {
		x.refers(from, r)
	}
}

// addImplements expects an implements edge from every type that is no
// interface to every interface with methods whose method set its own holds.
func (x *expectation) addImplements() {
	for _, ty := range x.w.types {
		if ty.form == "interface" {
			continue
		}
		have := methodSet(ty)
		for _, iface := range x.w.types {
			want := ifaceMethods(iface)
			if iface.form != "interface" || len(want) == 0 {
				continue
			}
			holds := true
			for id, sig := range want {
				holds = holds && have[id] != nil && canonSig(have[id]) == canonSig(sig)
			}
			if holds {
				x.edge(graph.EdgeKindImplements, typeIdentity(ty), typeIdentity(iface), graph.SourceExtracted)
			}
		}
	}
}

func (x *expectation) node(id string, kind graph.NodeKind, form string, at diag.Position, summary string, attrs map[string][]string) {
	x.nodes[id] = graph.Node{
		Id: id, Kind: kind, Form: form, Layer: graph.LayerCode, Source: graph.SourceExtracted, Origin: at,
		Summary: summary, Attrs: attrs,
	}
}

// edge expects an edge; a declared one stays when a derived one would replace it.
func (x *expectation) edge(kind graph.EdgeKind, from, to string, source graph.Source) edgeKey {
	key := edgeKey{kind, from, to}
	if _, ok := x.edges[key]; !ok {
		x.edges[key] = graph.Edge{Kind: kind, From: from, To: to, Source: source}
	}
	return key
}

func lowerFirst(name string) string {
	if !token.IsExported(name) {
		return name
	}
	return strings.ToLower(name[:1]) + name[1:]
}

// design writes a type expression in the design's notation (docs/design.md §4).
func (x *expectation) design(e *gexpr) string {
	switch e.kind {
	case "basic":
		return map[string]string{"bool": "bool", "int": "int", "float64": "float", "string": "string", "int64": "int64"}[e.basic]
	case "raw", "error":
		return cmp.Or(e.basic, "error")
	case "named":
		if targets := x.realized[e.named]; len(targets) > 0 {
			return targets[0]
		}
		return typeIdentity(e.named)
	case "ext":
		return "go:" + e.ext[0] + "." + e.ext[2]
	case "time":
		return "time"
	case "duration":
		return "duration"
	case "pointer":
		return "optional<" + x.design(e.elem) + ">"
	case "slice":
		return "list<" + x.design(e.elem) + ">"
	case "bytes":
		return "bytes"
	case "map":
		return "map<" + x.design(&gexpr{kind: "basic", basic: e.basic}) + ", " + x.design(e.elem) + ">"
	default:
		return "set<" + x.design(&gexpr{kind: "basic", basic: e.basic}) + ">"
	}
}

func (x *expectation) signature(sig *gsig) string {
	var params []string
	for _, p := range sig.params {
		params = append(params, cmp.Or(p.name, "_")+": "+x.design(p.typ))
	}
	out := "(" + strings.Join(params, ", ") + ")"
	results := sig.results
	raises := len(results) > 0 && results[len(results)-1].kind == "error"
	if raises {
		results = results[:len(results)-1]
	}
	var written []string
	for _, r := range results {
		written = append(written, x.design(r))
	}
	switch len(written) {
	case 0:
	case 1:
		out += " -> " + written[0]
	default:
		out += " -> (" + strings.Join(written, ", ") + ")"
	}
	if raises {
		out += " raises error"
	}
	return out
}

// canonSig writes a signature's Go types with package paths, so that two
// signatures are identical exactly when they write the same.
func canonSig(sig *gsig) string {
	var params, results []string
	for _, p := range sig.params {
		params = append(params, canon(p.typ))
	}
	for _, r := range sig.results {
		results = append(results, canon(r))
	}
	return "(" + strings.Join(params, ",") + ")(" + strings.Join(results, ",") + ")"
}

func canon(e *gexpr) string {
	switch e.kind {
	case "named":
		return typeIdentity(e.named)
	case "ext":
		return e.ext[0] + "." + e.ext[2]
	case "pointer", "slice", "map":
		return e.kind + "[" + e.basic + "]" + canon(e.elem)
	}
	return e.kind + "[" + e.basic + "]"
}
