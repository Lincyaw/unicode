// unimplemented is the message of the panic that is the whole body of a stub
// (docs/design.md §6.1).
const unimplemented = "unicode: unimplemented"

// extraction builds the code layer of the loaded packages: first a node for
// every package, file, type, function and method with the edges of their
// bindings, then the attrs written in the design's notation, then the other
// edges.
type extraction struct {
	root        string
	nodes       map[string]graph.Node
	edges       map[edgeKey]*graph.Edge
	sites       map[edgeKey][]diag.Position
	declared    []declared
	bindings    map[bindingKey]bool
	realizes    map[string][]string // a type's identity to the design types it realizes
	predicates  map[string]bool     // the operations that carry a checks binding
	values      map[string][]string // a type's identity to its constants' enum values
	vars        map[string][]initializer
	varUses     map[string]varUse
	diagnostics []diag.Diagnostic
}

type edgeKey struct {
	kind     graph.EdgeKind
	from, to string
}

// declared is a declaration that is a node: a type, a function, a method,
// or a method an interface declares.
type declared struct {
	id   string
	pkg  *packages.Package
	file sourceFile
	pos  token.Pos       // of its name
	spec *ast.TypeSpec   // a type's
	name *types.TypeName // a type's
	decl *ast.FuncDecl   // a function's or a method's; an interface's method has none
	fn   *types.Func     // a function's or a method's
}

func extract(l loaded) lang.Extracted {
	x := &extraction{
		root:       l.root,
		nodes:      map[string]graph.Node{},
		edges:      map[edgeKey]*graph.Edge{},
		sites:      map[edgeKey][]diag.Position{},
		bindings:   map[bindingKey]bool{},
		realizes:   map[string][]string{},
		predicates: map[string]bool{},
		values:     map[string][]string{},
		vars:       map[string][]initializer{},
		varUses:    map[string]varUse{},
	}
	for _, p := range l.packages {
		x.addPackage(p)
	}
	x.addShapes()
	x.addCandidates()
	x.substituteSignatures()
	for _, d := range x.declared {
		if d.name != nil {
			x.addTypeEdges(d)
		} else {
			x.addFuncEdges(d)
		}
	}
	x.addImplements()
	return x.result()
}

func (x *extraction) addPackage(p *packages.Package) {
	files := filesUnder(x.root, p)
	pkgID := "go:" + p.PkgPath
	// The package is written where its doc comment is, or else in its first file.
	written := files[0].syntax
	for _, f := range files {
		if f.syntax.Doc != nil {
			written = f.syntax
			break
		}
	}
	x.addNode(graph.Node{
		Id: pkgID, Kind: graph.NodeKindContainer, Form: "package", Origin: x.position(p, written.Package),
		Summary: synopsis(written.Doc), Attrs: map[string][]string{"language": {language}, "path": {p.PkgPath}},
	})
	for _, f := range files {
		fileID := "file:" + f.rel
		attrs := map[string][]string{"language": {language}, "path": {f.rel}}
		if unicodeGenerated(f.syntax) {
			attrs["generated"] = []string{"true"}
		}
		if globals := globalsDigest(f.syntax); globals != "" {
			attrs["globals"] = []string{globals}
		}
		x.addNode(graph.Node{
			Id: fileID, Kind: graph.NodeKindContainer, Form: "file", Origin: x.position(p, f.syntax.Package),
			Attrs: attrs,
		})
		x.addEdge(graph.EdgeKindContains, pkgID, fileID, x.position(p, f.syntax.Package))
		for _, spec := range f.syntax.Imports {
			if imported, err := strconv.Unquote(spec.Path.Value); err == nil {
				x.addEdge(graph.EdgeKindImports, fileID, "go:"+imported, x.position(p, spec.Pos()))
			}
		}
		docs := map[*ast.CommentGroup]bound{}
		for _, decl := range f.syntax.Decls {
			x.addDecl(p, f, fileID, decl, docs)
		}
		x.readBindings(p, f, fileID, docs)
	}
}

const unicodeGeneratedHeader = "// Code generated by unicode. DO NOT EDIT."

func unicodeGenerated(file *ast.File) bool {
	for _, group := range file.Comments {
		for _, comment := range group.List {
			if comment.Slash < file.Package && comment.Text == unicodeGeneratedHeader {
				return true
			}
		}
	}
	return false
}

// addDecl adds the nodes of a declaration and records whose doc comment is
// whose; a constant adds an enum value to its type, and a variable records
// its value.
func (x *extraction) addDecl(p *packages.Package, f sourceFile, fileID string, decl ast.Decl, docs map[*ast.CommentGroup]bound) {
	switch decl := decl.(type) {
	case *ast.GenDecl:
		for _, s := range decl.Specs {
			switch spec := s.(type) {
			case *ast.TypeSpec:
				x.addType(p, f, fileID, typeDoc(decl, spec), spec, docs)
			case *ast.ValueSpec:
				x.addValues(p, spec)
				x.addInitializers(p, spec)
			}
		}
	case *ast.FuncDecl:
		fn, ok := p.TypesInfo.Defs[decl.Name].(*types.Func)
		if !ok || !funcIsNode(decl) {
			return
		}
		form, parent := "func", fileID
		if decl.Recv != nil {
			form, parent = "method", typeID(receiver(fn).Obj())
		}
		x.addOp(declared{id: funcID(fn), pkg: p, file: f, pos: decl.Name.Pos(), decl: decl, fn: fn}, form, parent, decl.Doc,
			testKind(p.TypesInfo, f, decl, fn), isStub(p.TypesInfo, decl.Body), docs)
	}
}

// funcIsNode tells whether a function declaration is a node. Neither a
// function named _ nor an init function has an identity: a package may
// declare several of each.
func funcIsNode(decl *ast.FuncDecl) bool {
	return decl.Name.Name != "_" && (decl.Recv != nil || decl.Name.Name != "init")
}

// typeIsNode tells whether a type spec is a node; an alias is not.
func typeIsNode(spec *ast.TypeSpec) bool { return !spec.Assign.IsValid() }

func (x *extraction) addType(p *packages.Package, f sourceFile, fileID string, doc *ast.CommentGroup, spec *ast.TypeSpec, docs map[*ast.CommentGroup]bound) {
	name, ok := p.TypesInfo.Defs[spec.Name].(*types.TypeName)
	if !ok || !typeIsNode(spec) {
		return
	}
	d := declared{id: typeID(name), pkg: p, file: f, pos: spec.Name.Pos(), spec: spec, name: name}
	x.addNode(graph.Node{
		Id: d.id, Kind: graph.NodeKindType, Form: typeForm(name), Origin: x.position(p, d.pos),
		Summary: synopsis(doc), Attrs: map[string][]string{"name": {name.Name()}, "declaration": {declarationDigest(spec)}},
	})
	x.addEdge(graph.EdgeKindContains, fileID, d.id, x.position(p, d.pos))
	x.declared = append(x.declared, d)
	if doc != nil {
		docs[doc] = bound{id: d.id, isType: true}
	}
	iface, ok := spec.Type.(*ast.InterfaceType)
	if !ok {
		return
	}
	for _, field := range iface.Methods.List {
		if len(field.Names) == 0 {
			continue // an embedded interface
		}
		if fn, ok := p.TypesInfo.Defs[field.Names[0]].(*types.Func); ok {
			method := declared{id: d.id + "." + fn.Name(), pkg: p, file: f, pos: field.Names[0].Pos(), fn: fn}
			x.addOp(method, "abstract", d.id, field.Doc, "none", false, docs)
		}
	}
}

func (x *extraction) addOp(d declared, form, parent string, doc *ast.CommentGroup, testKind string, stub bool, docs map[*ast.CommentGroup]bound) {
	attrs := map[string][]string{"testKind": {testKind}, "stub": {strconv.FormatBool(stub)}}
	if d.decl != nil && d.decl.Body != nil {
		attrs["body"] = []string{bodyDigest(d.decl.Body)}
	}
	x.addNode(graph.Node{
		Id: d.id, Kind: graph.NodeKindOp, Form: form, Origin: x.position(d.pkg, d.pos), Summary: synopsis(doc), Attrs: attrs,
	})
	x.addEdge(graph.EdgeKindContains, parent, d.id, x.position(d.pkg, d.pos))
	x.declared = append(x.declared, d)
	if doc != nil {
		docs[doc] = bound{id: d.id, isMethod: form != "func"}
	}
}

// addValues adds each constant of a package-level type whose underlying type
// is string to that type's enum values, in the order of the source.
func (x *extraction) addValues(p *packages.Package, spec *ast.ValueSpec) {
	for _, ident := range spec.Names {
		c, ok := p.TypesInfo.Defs[ident].(*types.Const)
		if !ok {
			continue
		}
		named, ok := types.Unalias(c.Type()).(*types.Named)
		if !ok || named.Obj().Pkg() == nil || named.Obj().Pkg().Path() != p.PkgPath || !packageLevelType(named) {
			continue
		}
		if basic, ok := named.Underlying().(*types.Basic); ok && basic.Kind() == types.String {
			id := typeID(named.Obj())
			x.values[id] = append(x.values[id], enumValueName(c.Name(), named.Obj().Name()))
		}
	}
}

// addTypeEdges adds the refers edges of a type to the types its declaration
// mentions, and its extends edges to the types it embeds.
func (x *extraction) addTypeEdges(d declared) {
	origin := x.position(d.pkg, d.pos)
	refer := func(t *types.Named) { x.addEdge(graph.EdgeKindRefers, d.id, typeID(t.Obj()), origin) }
	embed := func(t types.Type) {
		if named := namedOf(t); named != nil {
			x.addEdge(graph.EdgeKindExtends, d.id, typeID(named.Obj()), origin)
		}
	}
	switch rhs := types.Unalias(d.pkg.TypesInfo.TypeOf(d.spec.Type)).(type) {
	case *types.Struct:
		for field := range rhs.Fields() {
			if field.Embedded() {
				embed(field.Type())
			} else {
				mentioned(field.Type(), refer)
			}
		}
	case *types.Interface:
		// The types of the methods it declares are those methods' references.
		for t := range rhs.EmbeddedTypes() {
			embed(t)
		}
	default:
		mentioned(rhs, refer)
	}
}

// addFuncEdges adds the refers edges of a function to the types of its
// parameters and results and to the types its body names or gives its
// variables, and its calls edges: those of its body, and those of the
// closures in the package-level variables its body uses.
func (x *extraction) addFuncEdges(d declared) {
	origin := x.position(d.pkg, d.pos)
	refer := func(t *types.Named) {
		if packageLevelType(t) {
			x.addEdge(graph.EdgeKindRefers, d.id, typeID(t.Obj()), origin)
		}
	}
	sig := d.fn.Signature()
	for _, tuple := range []*types.Tuple{sig.Params(), sig.Results()} {
		for v := range tuple.Variables() {
			mentioned(v.Type(), refer)
		}
	}
	if d.decl == nil || d.decl.Body == nil {
		return
	}
	info := d.pkg.TypesInfo
	var vars []string
	ast.Inspect(d.decl.Body, func(n ast.Node) bool {
		switch n := n.(type) {
		case *ast.Ident:
			if name, ok := info.Uses[n].(*types.TypeName); ok {
				mentioned(name.Type(), refer)
			} else if v, ok := info.Defs[n].(*types.Var); ok {
				mentioned(v.Type(), refer)
			} else if id, ok := packageVar(info, n); ok {
				vars = append(vars, id)
			}
		case *ast.CallExpr:
			if callee, name, ok := staticCall(info, n); ok {
				x.addCall(d.id, call{callee: callee, site: x.position(d.pkg, name.Pos())})
			}
		}
		return true
	})
	x.addClosureCalls(d.id, vars)
}

// call is a static call: the function it calls, and where it names it.
type call struct {
	callee string
	site   diag.Position
}

func (x *extraction) addCall(from string, c call) {
	key := x.addEdge(graph.EdgeKindCalls, from, c.callee, c.site)
	x.sites[key] = append(x.sites[key], c.site)
}

// staticCall is the identity of the package-level function or method that a
// call statically calls, and the identifier that names it.
func staticCall(info *types.Info, n *ast.CallExpr) (string, *ast.Ident, bool) {
	callee, ok := typeutil.Callee(info, n).(*types.Func)
	name := calleeName(n.Fun)
	if !ok || name == nil || !packageLevel(callee) {
		return "", nil, false
	}
	return funcID(callee.Origin()), name, true
}

// addImplements adds an implements edge from every type that is not an
// interface to every interface with methods whose method set its pointer's
// method set holds. Methods are compared by their package-qualified names and
// signatures, so the variant a package was loaded in does not matter.
func (x *extraction) addImplements() {
	var concrete, interfaces []declared
	for _, d := range x.declared {
		if d.name == nil || d.name.Type().(*types.Named).TypeParams().Len() > 0 {
			continue
		}
		if iface, ok := d.name.Type().Underlying().(*types.Interface); !ok {
			concrete = append(concrete, d)
		} else if iface.IsMethodSet() && iface.NumMethods() > 0 {
			interfaces = append(interfaces, d)
		}
	}
	identity := nativeIdentity{packages: map[string]*types.Package{}, named: map[string][]nativeNamed{}}
	for _, c := range concrete {
		have := methodKeys(types.NewMethodSet(types.NewPointer(c.name.Type())), &identity)
		for _, i := range interfaces {
			want := methodKeys(types.NewMethodSet(i.name.Type()), &identity)
			if implementsAll(have, want) {
				x.addEdge(graph.EdgeKindImplements, c.id, i.id, x.position(c.pkg, c.pos))
			}
		}
	}
}

// Native identity uses go/types, with named objects interned by package path
// across test variants. Instantiation arguments retain their native identities.
type nativeNamed struct {
	arguments []types.Type
	typ       *types.Named
}
type nativeIdentity struct {
	packages map[string]*types.Package
	named    map[string][]nativeNamed
}

func (n *nativeIdentity) pkg(p *types.Package) *types.Package {
	if p == nil {
		return nil
	}
	if canonical := n.packages[p.Path()]; canonical != nil {
		return canonical
	}
	canonical := types.NewPackage(p.Path(), p.Name())
	n.packages[p.Path()] = canonical
	return canonical
}
func (n *nativeIdentity) tuple(tuple *types.Tuple) *types.Tuple {
	vars := make([]*types.Var, tuple.Len())
	for i := range vars {
		v := tuple.At(i)
		vars[i] = types.NewVar(v.Pos(), n.pkg(v.Pkg()), v.Name(), n.typ(v.Type()))
	}
	return types.NewTuple(vars...)
}
func (n *nativeIdentity) typ(t types.Type) types.Type {
	t = types.Unalias(t)
	switch t := t.(type) {
	case *types.Named:
		arguments := make([]types.Type, t.TypeArgs().Len())
		for i := range arguments {
			arguments[i] = n.typ(t.TypeArgs().At(i))
		}
		obj := t.Origin().Obj()
		path := ""
		if obj.Pkg() != nil {
			path = obj.Pkg().Path()
		}
		key := path + "\x00" + obj.Name()
		for _, entry := range n.named[key] {
			same := len(arguments) == len(entry.arguments)
			for i := range arguments {
				if !same || !types.Identical(arguments[i], entry.arguments[i]) {
					same = false
					break
				}
			}
			if same {
				return entry.typ
			}
		}
		canonical := types.NewNamed(types.NewTypeName(obj.Pos(), n.pkg(obj.Pkg()), obj.Name(), nil), types.Typ[types.Invalid], nil)
		n.named[key] = append(n.named[key], nativeNamed{arguments, canonical})
		return canonical
	case *types.Signature:
		return types.NewSignatureType(nil, nil, nil, n.tuple(t.Params()), n.tuple(t.Results()), t.Variadic())
	case *types.Pointer:
		return types.NewPointer(n.typ(t.Elem()))
	case *types.Slice:
		return types.NewSlice(n.typ(t.Elem()))
	case *types.Array:
		return types.NewArray(n.typ(t.Elem()), t.Len())
	case *types.Map:
		return types.NewMap(n.typ(t.Key()), n.typ(t.Elem()))
	case *types.Chan:
		return types.NewChan(t.Dir(), n.typ(t.Elem()))
	case *types.Struct:
		fields := make([]*types.Var, t.NumFields())
		tags := make([]string, len(fields))
		for i := range fields {
			f := t.Field(i)
			fields[i] = types.NewField(f.Pos(), n.pkg(f.Pkg()), f.Name(), n.typ(f.Type()), f.Embedded())
			tags[i] = t.Tag(i)
		}
		return types.NewStruct(fields, tags)
	case *types.Interface:
		t.Complete()
		if !t.IsMethodSet() {
			return t
		}
		methods := make([]*types.Func, t.NumMethods())
		for i := range methods {
			m := t.Method(i)
			methods[i] = types.NewFunc(m.Pos(), n.pkg(m.Pkg()), m.Name(), n.typ(m.Type()).(*types.Signature))
		}
		return types.NewInterfaceType(methods, nil).Complete()
	default:
		return t
	}
}

// methodKeys retains package-qualified method names and native signatures.
func methodKeys(set *types.MethodSet, identity *nativeIdentity) map[string]types.Type {
	keys := map[string]types.Type{}
	for sel := range set.Methods() {
		m := sel.Obj().(*types.Func)
		keys[m.Id()] = identity.typ(m.Type())
	}
	return keys
}
func implementsAll(have, want map[string]types.Type) bool {
	for id, signature := range want {
		if !types.Identical(have[id], signature) {
			return false
		}
	}
	return true
}

func (x *extraction) addNode(n graph.Node) {
	n.Layer, n.Source = graph.LayerCode, graph.SourceExtracted
	x.nodes[n.Id] = n
}

// addEdge adds an extracted edge and returns its key; an edge already present
// stays as it is. The result keeps only the extracted edges whose ends are
// both nodes, so an edge may be added before its ends are.
func (x *extraction) addEdge(kind graph.EdgeKind, from, to string, origin diag.Position) edgeKey {
	key := edgeKey{kind, from, to}
	if _, ok := x.edges[key]; !ok {
		x.edges[key] = &graph.Edge{Kind: kind, From: from, To: to, Source: graph.SourceExtracted, Origin: origin}
	}
	return key
}

// result writes the nodes sorted by identity, the edges by kind, start and
// end, each call's sites in the order of the source, and the diagnostics by
// position.
func (x *extraction) result() lang.Extracted {
	out := lang.Extracted{Diagnostics: x.diagnostics}
	slices.SortFunc(out.Diagnostics, func(a, b diag.Diagnostic) int {
		return cmp.Or(comparePositions(a.Position, b.Position), cmp.Compare(a.Code, b.Code))
	})
	for _, id := range slices.Sorted(maps.Keys(x.nodes)) {
		out.Fragment.Nodes = append(out.Fragment.Nodes, x.nodes[id])
	}
	keys := slices.SortedFunc(maps.Keys(x.edges), func(a, b edgeKey) int {
		return cmp.Or(cmp.Compare(a.kind, b.kind), cmp.Compare(a.from, b.from), cmp.Compare(a.to, b.to))
	})
	for _, key := range keys {
		e := *x.edges[key]
		_, fromNode := x.nodes[e.From]
		_, toNode := x.nodes[e.To]
		if e.Source == graph.SourceExtracted && (!fromNode || !toNode) {
			continue
		}
		if sites := x.sites[key]; len(sites) > 0 {
			slices.SortFunc(sites, comparePositions)
			e.Origin = sites[0]
			e.Attrs = map[string][]string{"sites": {}}
			for _, s := range sites {
				e.Attrs["sites"] = append(e.Attrs["sites"], fmt.Sprintf("%s:%d:%d", s.Path, s.Line, s.Column))
			}
		}
		out.Fragment.Edges = append(out.Fragment.Edges, e)
	}
	return out
}

func comparePositions(a, b diag.Position) int {
	return cmp.Or(cmp.Compare(a.Path, b.Path), cmp.Compare(a.Line, b.Line), cmp.Compare(a.Column, b.Column))
}

func (x *extraction) position(p *packages.Package, pos token.Pos) diag.Position {
	at := p.Fset.Position(pos)
	rel, err := filepath.Rel(x.root, at.Filename)
	if err != nil {
		rel = at.Filename
	}
	return diag.Position{Path: filepath.ToSlash(rel), Line: at.Line, Column: at.Column}
}

func typeID(name *types.TypeName) string { return "go:" + name.Pkg().Path() + "." + name.Name() }

// funcID is the identity of a package-level function, or of a method under
// its receiver's type.
func funcID(fn *types.Func) string {
	if recv := receiver(fn); recv != nil {
		return typeID(recv.Obj()) + "." + fn.Name()
	}
	return "go:" + fn.Pkg().Path() + "." + fn.Name()
}

// receiver is the named type a method is declared on, or nil for a function
// or a method of an unnamed interface.
func receiver(fn *types.Func) *types.Named {
	recv := fn.Signature().Recv()
	if recv == nil {
		return nil
	}
	return namedOf(recv.Type())
}

// namedOf is the named type t is, or points to, or nil.
func namedOf(t types.Type) *types.Named {
	if p, ok := types.Unalias(t).(*types.Pointer); ok {
		t = p.Elem()
	}
	named, _ := types.Unalias(t).(*types.Named)
	if named == nil {
		return nil
	}
	return named.Origin()
}

// packageLevel tells whether a function is declared at the package level,
// directly or as a method of a package-level type: a type declared in a
// function body shares its name's identity with one of the package.
func packageLevel(fn *types.Func) bool {
	if fn.Pkg() == nil {
		return false
	}
	if fn.Signature().Recv() == nil {
		return true
	}
	recv := receiver(fn)
	return recv != nil && packageLevelType(recv)
}

// packageLevelType tells whether a named type is declared at the package level.
func packageLevelType(t *types.Named) bool {
	obj := t.Obj()
	return obj.Pkg() != nil && obj.Parent() == obj.Pkg().Scope()
}

// mentioned calls visit with every named type that t mentions, without
// looking inside the named types themselves.
func mentioned(t types.Type, visit func(*types.Named)) {
	switch t := types.Unalias(t).(type) {
	case *types.Named:
		if t.Obj().Pkg() != nil {
			visit(t.Origin())
		}
		for arg := range t.TypeArgs().Types() {
			mentioned(arg, visit)
		}
	case *types.Pointer:
		mentioned(t.Elem(), visit)
	case *types.Slice:
		mentioned(t.Elem(), visit)
	case *types.Array:
		mentioned(t.Elem(), visit)
	case *types.Chan:
		mentioned(t.Elem(), visit)
	case *types.Map:
		mentioned(t.Key(), visit)
		mentioned(t.Elem(), visit)
	case *types.Signature:
		mentioned(t.Params(), visit)
		mentioned(t.Results(), visit)
	case *types.Tuple:
		for v := range t.Variables() {
			mentioned(v.Type(), visit)
		}
	case *types.Struct:
		for field := range t.Fields() {
			mentioned(field.Type(), visit)
		}
	case *types.Interface:
		for m := range t.Methods() {
			mentioned(m.Type(), visit)
		}
	}
}

// calleeName is the identifier that names the function a call calls, or nil.
func calleeName(fun ast.Expr) *ast.Ident {
	switch fun := ast.Unparen(fun).(type) {
	case *ast.Ident:
		return fun
	case *ast.SelectorExpr:
		return fun.Sel
	case *ast.IndexExpr:
		return calleeName(fun.X)
	case *ast.IndexListExpr:
		return calleeName(fun.X)
	}
	return nil
}

func typeForm(name *types.TypeName) string {
	switch name.Type().Underlying().(type) {
	case *types.Struct:
		return "struct"
	case *types.Interface:
		return "interface"
	}
	return "defined"
}

// typeDoc is a type's doc comment: its spec's in a parenthesized
// declaration, the declaration's otherwise.
func typeDoc(decl *ast.GenDecl, spec *ast.TypeSpec) *ast.CommentGroup {
	if decl.Lparen.IsValid() {
		return spec.Doc
	}
	return decl.Doc
}

// synopsis is the first sentence of a doc comment, without its directives.
func synopsis(group *ast.CommentGroup) string {
	if group == nil {
		return ""
	}
	return new(doc.Package).Synopsis(group.Text())
}

// testKind classifies a function the way go test does (docs/design.md §4):
// FuzzX(*testing.F) is a fuzz test; TestX(*testing.T) is a property when it
// calls rapid.Check and an example otherwise.
func testKind(info *types.Info, f sourceFile, decl *ast.FuncDecl, fn *types.Func) string {
	sig := fn.Signature()
	if decl.Recv != nil || !strings.HasSuffix(f.rel, "_test.go") || sig.TypeParams().Len() > 0 ||
		sig.Params().Len() != 1 || sig.Results().Len() != 0 {
		return "none"
	}
	param := types.TypeString(sig.Params().At(0).Type(), pathQualifier)
	switch {
	case isTestName(fn.Name(), "Fuzz") && param == "*testing.F":
		return "fuzz"
	case isTestName(fn.Name(), "Test") && param == "*testing.T" && callsRapidCheck(info, decl.Body):
		return "property"
	case isTestName(fn.Name(), "Test") && param == "*testing.T":
		return "example"
	}
	return "none"
}

// isTestName tells whether name is prefix followed by nothing or by a
// character that is not a lower-case letter, as go test requires.
func isTestName(name, prefix string) bool {
	rest, ok := strings.CutPrefix(name, prefix)
	if !ok {
		return false
	}
	r, _ := utf8.DecodeRuneInString(rest)
	return rest == "" || !unicode.IsLower(r)
}

func callsRapidCheck(info *types.Info, body *ast.BlockStmt) bool {
	found := false
	ast.Inspect(body, func(n ast.Node) bool {
		if call, ok := n.(*ast.CallExpr); ok {
			fn, ok := typeutil.Callee(info, call).(*types.Func)
			found = found || ok && fn.Pkg() != nil && fn.Pkg().Path() == "pgregory.net/rapid" && fn.Name() == "Check"
		}
		return !found
	})
	return found
}

// isStub tells whether a body is exactly the unimplemented marker.
func isStub(info *types.Info, body *ast.BlockStmt) bool {
	if body == nil || len(body.List) != 1 {
		return false
	}
	stmt, ok := body.List[0].(*ast.ExprStmt)
	if !ok {
		return false
	}
	call, ok := stmt.X.(*ast.CallExpr)
	if !ok || len(call.Args) != 1 || call.Ellipsis.IsValid() {
		return false
	}
	fun, ok := call.Fun.(*ast.Ident)
	if builtin, isBuiltin := info.Uses[fun].(*types.Builtin); !ok || !isBuiltin || builtin.Name() != "panic" {
		return false
	}
	lit, ok := call.Args[0].(*ast.BasicLit)
	if !ok || lit.Kind != token.STRING {
		return false
	}
	message, err := strconv.Unquote(lit.Value)
	return err == nil && message == unimplemented
}

// pathQualifier writes a package by its path.
func pathQualifier(p *types.Package) string { return p.Path() }
