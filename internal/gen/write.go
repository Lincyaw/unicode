const generatedMarker = "Code generated by unicode. DO NOT EDIT."

// Write preflights every edit before changing any file. Each replacement is
// atomic; a later I/O failure does not undo files already written.
//
//uc:realizes gen.write
func Write(root string, edits []lang.Edit) []diag.Diagnostic {
	modes, ds := preflightEdits(root, edits, ioDiagnostic)
	if len(ds) > 0 {
		return ds
	}
	ordered := slices.Clone(edits)
	slices.SortFunc(ordered, func(a, b lang.Edit) int { return strings.Compare(a.Path, b.Path) })
	for _, edit := range ordered {
		target := filepath.Join(root, filepath.FromSlash(edit.Path))
		if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
			return []diag.Diagnostic{ioDiagnostic(edit.Path, err)}
		}
		if err := writeEdit(target, edit, modes[edit.Path]); err != nil {
			return []diag.Diagnostic{ioDiagnostic(edit.Path, err)}
		}
	}
	return nil
}

// preflightEdits applies the same path and ownership rules to writing and
// checking. It never creates directories or changes repository entries.
func preflightEdits(root string, edits []lang.Edit, ioFailure func(string, error) diag.Diagnostic) (map[string]os.FileMode, []diag.Diagnostic) {
	var ds []diag.Diagnostic
	seen := map[string]bool{}
	modes := map[string]os.FileMode{}
	for _, edit := range edits {
		if !filepath.IsLocal(edit.Path) || edit.Path == "." || strings.ContainsAny(edit.Path, "\\\x00") || path.Clean(edit.Path) != edit.Path {
			ds = append(ds, diagnostic("gen.invalid-path", edit.Path, "the generated path is not a clean relative repository file path", "use a slash-separated file path inside the repository without . or .. segments"))
			continue
		}
		if seen[edit.Path] {
			ds = append(ds, diagnostic("gen.duplicate-path", edit.Path, "more than one edit targets this path", "give every edit a distinct repository path"))
			continue
		}
		seen[edit.Path] = true
		mode, d := preflight(root, edit.Path, edit.CreateOnly, ioFailure)
		if d != nil {
			ds = append(ds, *d)
			continue
		}
		modes[edit.Path] = mode
	}
	for _, edit := range edits {
		for parent := path.Dir(edit.Path); parent != "." && parent != "/"; parent = path.Dir(parent) {
			if seen[parent] {
				ds = append(ds, diagnostic("gen.invalid-path", edit.Path, "another edit targets a parent of this file", "give generated files paths that are not parents of one another"))
				break
			}
		}
	}
	sortDiagnostics(ds)
	return modes, ds
}

func preflight(root, rel string, createOnly bool, ioFailure func(string, error) diag.Diagnostic) (os.FileMode, *diag.Diagnostic) {
	parts := strings.Split(rel, "/")
	current := root
	for i := -1; i < len(parts); i++ {
		if i >= 0 {
			current = filepath.Join(current, parts[i])
		}
		info, err := os.Lstat(current)
		if errors.Is(err, os.ErrNotExist) {
			continue
		}
		if err != nil {
			d := ioFailure(rel, err)
			return 0, &d
		}
		if info.Mode()&os.ModeSymlink != 0 {
			d := diagnostic("gen.symlink", rel, "the generated path or one of its parents is a symbolic link", "replace the symbolic link with a directory or choose another generated path")
			return 0, &d
		}
		if i < len(parts)-1 {
			if !info.IsDir() {
				d := diagnostic("gen.invalid-path", rel, "a parent of the generated file is not a directory", "choose a path whose parents are directories")
				return 0, &d
			}
			continue
		}
		if !info.Mode().IsRegular() {
			d := diagnostic("gen.unowned-file", rel, "the target is not a regular tool-generated file", "choose a new generated path or remove the conflicting entry")
			return 0, &d
		}
		if createOnly {
			d := diagnostic("gen.unowned-file", rel, "a create-only skeleton target already exists", "rebuild the generation plan after extracting the existing source; never overwrite a skeleton")
			return 0, &d
		}
		src, err := os.ReadFile(current)
		if err != nil {
			d := ioFailure(rel, err)
			return 0, &d
		}
		if !hasMarker(src) {
			d := diagnostic("gen.unowned-file", rel, "the existing file has no unicode generation marker", "move the handwritten file or choose a new generated path")
			return 0, &d
		}
		return info.Mode().Perm(), nil
	}
	return 0o644, nil
}

// writeEdit never replaces a skeleton, even if a target appears after preflight.
func writeEdit(target string, edit lang.Edit, mode os.FileMode) error {
	if !edit.CreateOnly {
		return maybe.WriteFile(target, edit.Content, mode)
	}
	file, err := os.OpenFile(target, os.O_WRONLY|os.O_CREATE|os.O_EXCL, mode)
	if err != nil {
		return err
	}
	n, writeErr := file.Write(edit.Content)
	if writeErr == nil && n != len(edit.Content) {
		writeErr = io.ErrShortWrite
	}
	err = errors.Join(writeErr, file.Close())
	if err != nil {
		err = errors.Join(err, os.Remove(target))
	}
	return err
}

func hasMarker(src []byte) bool {
	for _, line := range bytes.Split(src, []byte{'\n'}) {
		text := strings.TrimSpace(string(line))
		if text == "// "+generatedMarker || text == "# "+generatedMarker {
			return true
		}
		if text != "" && !strings.HasPrefix(text, "//") && !strings.HasPrefix(text, "#") {
			return false
		}
	}
	return false
}
